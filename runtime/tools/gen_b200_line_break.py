#!/usr/bin/env python3
"""Write runtime/native/b200unicode/b200linebreak_table.h, the DLL's copy of src/vf2_line_break.FALLBACK_RANGES.

    gen_b200_line_break.py [--check]

The table is written once, in Python (the patcher's own line wrapping uses it too); tests/test_line_break.py fails if
the committed header is not what render() gives. --check compares instead of writing.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
import vf2_line_break as L  # noqa: E402

H_OUT = ROOT / "runtime" / "native" / "b200unicode" / "b200linebreak_table.h"
NAMES = {L.IDEOGRAPHIC: "LbIdeographic", L.CLOSING: "LbClosing", L.OPENING: "LbOpening"}


def render() -> str:
    rows = [f"{{ 0x{a:04X}, 0x{b:04X}, {NAMES[c]} }}," for a, b, c in L.FALLBACK_RANGES]
    lines, cur = [], "   "
    for row in rows:
        if len(cur) + len(row) + 1 > 118:
            lines.append(cur)
            cur = "   "
        cur += " " + row
    lines.append(cur)
    body = "\n".join(lines)
    return f"""// GENERATED by runtime/tools/gen_b200_line_break.py from src/vf2_line_break.py (FALLBACK_RANGES). Do not edit.
//
// Line breaking without ICU (b200unicode_text.h NextLine): the CJK basics of UAX #14. Used where Windows has no icu.dll
// (before Windows 10 1903) and by the test DLL that proves the C++ and the Python wrap the same.
//   LbIdeographic: a letter of a script written without spaces: a line may break before and after it;
//   LbClosing:     closing punctuation and the Japanese small kana: no line starts with it;
//   LbOpening:     opening punctuation: no line ends with it.
#pragma once

namespace ut {{

enum {{ LbOther = 0, LbIdeographic = 1, LbClosing = 2, LbOpening = 3 }};

struct LbRange {{ unsigned first, last; unsigned char cls; }};
static const LbRange kLineBreakRanges[] = {{   // sorted, not overlapping
{body}
}};
static const unsigned kLineBreakRangeCount = {len(L.FALLBACK_RANGES)}u;

}}  // namespace ut
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if H_OUT.read_bytes().decode("utf-8").replace("\r\n", "\n") != text:
            print(f"{H_OUT} is not what this script writes", file=sys.stderr)
            return 1
        return 0
    H_OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {H_OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
