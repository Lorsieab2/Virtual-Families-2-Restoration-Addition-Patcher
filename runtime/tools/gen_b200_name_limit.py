#!/usr/bin/env python3
"""Write runtime/native/b200unicode/b200name_limit.h, the DLLs' copy of the one name limit.

    gen_b200_name_limit.py [--check]

The limit is written once, in Python: src/vf2_game_text.NAME_BOX_BYTES (1,200 bytes as stored, no separate character
cap). This script writes the C header from it; tests/test_name_limit.py fails if the committed header is not what
render() gives. --check compares instead of writing.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
import vf2_game_text as T  # noqa: E402

H_OUT = ROOT / "runtime" / "native" / "b200unicode" / "b200name_limit.h"


def render() -> str:
    return f"""// GENERATED by runtime/tools/gen_b200_name_limit.py from src/vf2_game_text.py (NAME_BOX_BYTES). Do not edit.
//
// The one name limit in C: every name box takes up to kNameBoxBytes bytes as stored, with no separate character cap
// (docs/UNICODE_TEXT.md, "Names up to 1,200 bytes"). tests/test_name_limit.py checks this file against the generator,
// so the number is written in Python and nowhere else. Included by:
//   * b200unicode.cpp for vf2unicode_b200.dll / vf2unicodefont_b200.dll (b200names.inc: the name boxes' limits);
//   * the same source built as vf2clip_b200.dll (b200clip.inc: a paste into a name box stops at the box's bytes);
//   * b200history.cpp (vf2history_b200.dll: a whole name from the Names file is at most kNameBoxBytes).
#pragma once

static const unsigned kNameBoxBytes = {T.NAME_BOX_BYTES};            // bytes of the stored form a name box holds (= TEXT_BOX_CEILING_BYTES)
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if H_OUT.read_bytes().decode("utf-8").replace("\r\n", "\n") != text:
            print(f"{H_OUT} is not what this script writes", file=sys.stderr)
            return 1
        return 0
    H_OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {H_OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
