def tier(body: int) -> str:
    """The store tier a body value comes from (the generators MaybeUpdateOutfits stocks the store with)."""
    if body in EXPANSION_BODIES:
        return "the patcher's Holiday outfits"
    if 0 <= body <= 31:
        return "Discount"
    if 32 <= body <= 43:
        return "Department"
    if 44 <= body <= 49:
        return "Designer"
    return "not a body the game makes"


def outfit_name(sex: int, body: int) -> str:
    """The patcher's Clothing and Hairstyles store name of a body value (outfit_store_entries)."""
    holiday = "Holiday " if body in EXPANSION_BODIES else ""
    return f"{SEXES[sex]} {holiday}Outfit Body {body:02d}"


def hairstyle_name(sex: int, head: int) -> str:
    """The patcher's store name of a head value (head_store_entries: its 100 hairstyles, 50 a sex)."""
    return f"{SEXES[sex]} Hairstyle {head:02d}"


def stage(age: int) -> str:
    """The family's words for an age (the game itself only scales below 14 and turns the head old at 45)."""
    years = age // YEAR
    if years < 1:
        return "baby"
    if years < 3:
        return "toddler"
    if years < 13:
        return "child"
    if years < 20:
        return "teen"
    if age >= OLD_HEAD_AGE:
        return "elder"
    return "adult"


# ------------------------------------------------------------------ the game's numbers


def body_scale(age: int) -> float:
    """CVillager::Scale: age / 700 + 0.5 below age 280 (float steps), else 1."""
    if age < CHILD_AGE:
        return pi.f32(pi.f32(age / 700.0) + 0.5)
    return 1.0


def head_scale(age: int) -> float:
    """The head's scale in every draw: (age / 14 + 80) / 100 below age 280 (float steps), else 1."""
    if age < CHILD_AGE:
        return pi.f32(pi.f32(pi.f32(age / 14.0) + 80.0) / 100.0)
    return 1.0


def percent(scale: float) -> int:
    """A scale as the whole percent the window's scaled draw takes: (int)(scale * 100), a float product."""
    return int(pi.f32(scale * 100.0))


_LINKS: dict | None = None


def links() -> dict:
    global _LINKS
    if _LINKS is None:
        _LINKS = json.loads(LINKS_FILE.read_text(encoding="utf-8"))
    return _LINKS


def link_entry(part: str, key: int, sex: int) -> dict:
    return links()[part][f"{key}/{1 if sex else 0}"]


def link(part: str, which: str, key: int, sex: int, row: int, scale: float) -> tuple[int, int]:
    """CAnimManager::GetScaledLinkTo{Next,Prev}Pt: a row of 50 or more uses row 49."""
    points = link_entry(part, key, sex)[which]
    row = row if row < ROWS else ROWS - 1
    x, y = points[row] if len(points) > 1 else points[0]
    return pi.scaled_link(x, scale), pi.scaled_link(y, scale)


def facing(frame: int) -> int:
    """CAnimManager::GetDirection(EAnimFrame), -1 when the game's table has none."""
    return int(links()["facing"].get(str(frame), -1))


# ------------------------------------------------------------------ what is drawn


@dataclass(frozen=True)
class Layer:
    """One draw: cell (col, row) of image `image`, or the whole picture `file` (relative to the game folder), its
    top-left at (x, y), at `percent` of its size. `what` names it (shadow, body, head, baby)."""
    what: str
    x: int
    y: int
    percent: int = 100
    image: int | None = None
    col: int = 0
    row: int = 0
    file: str | None = None
    centre: bool = False            # the blitter's centring flag: a scaled picture keeps its unscaled centre


@dataclass(frozen=True)
class Person:
    sex: int
    head: int
    body: int
    age: int = 400
    babies: int = 0                 # babies on the way (an expecting mother): 0-3


def _expansion_frame(sex: int, body: int, image: int, col: int) -> str | None:
    role = ROLES.get(image)
    if role is None or body not in EXPANSION_BODIES or not 0 <= col < ROLE_FRAMES[role]:
        return None
    return f"Images/VillagerBodies/{SEXES[sex]}/Body_{body:02d}/{role}/Frame{col:02d}.png"


def _detail_frame(sex: int, body: int) -> str | None:
    if body not in EXPANSION_BODIES:
        return None
    return f"Images/VillagerDetailBodies/{SEXES[sex]}/Body_{body:02d}/Frame00.png"


def _body_layer(person: Person, frame: int, x: int, y: int, pct: int, patched: bool, detail_screen: bool) -> Layer:
    entry = link_entry("body", frame, person.sex)
    image, col = entry["image"], entry["cell"]
    if patched:
        path = _detail_frame(person.sex, person.body) if image == 22 else \
            _expansion_frame(person.sex, person.body, image, col)
        if path is not None and (image != 22 or detail_screen):
            return Layer("body", x, y, pct, file=path)
    return Layer("body", x, y, pct, image=image, col=col, row=person.body)


def details_plan(person: Person, turn: int = 0, patched: bool = False, at: tuple = (0, 0)) -> list[Layer]:
    """CVillager::DrawDetailVillager(at): the Details screen's big body (frame 56) with its "next" point at
    `at`, and the big head (turn 0-2: the screen picks one at random) on its neck."""
    px, py = at
    s, hs = body_scale(person.age), head_scale(person.age)
    nx, ny = link("body", "next", DETAIL_FRAME, person.sex, person.body, s)
    bx, by = px - nx, py - ny
    body = _body_layer(person, DETAIL_FRAME, bx, by, percent(s), patched, True)
    vx, vy = link("body", "prev", DETAIL_FRAME, person.sex, person.body, s)
    direction = turn + 3 * (4 - turn // 3)          # the code's own sum: 12-14 for turns 0-2
    hx, hy = link("head", "next", direction, person.sex, person.head, hs)
    entry = link_entry("head", direction, person.sex)
    col = entry["cell"] + (IMAGES[entry["image"]][1] // 2 if person.age >= OLD_HEAD_AGE else 0)
    head = Layer("head", bx - hx + vx, by - hy + vy, percent(hs), image=entry["image"], col=col, row=person.head)
    return [body, head]


def house_plan(person: Person, frame: int, turn: int, shadow: bool = True, patched: bool = False,
               at: tuple = (0, 0)) -> list[Layer]:
    """CVillagerManager::DrawVillager at the house's 100% zoom, the villager's place `at`: its shadow, the body
    (frame 0-55) with its "next" point on the feet (CVillager::FeetPos: the place plus 28 x 81 scaled), the head
    (turn 0-11) on the neck, and an expecting mother's babies (DrawCarriedItems) behind her when the frame faces
    NE, NW or N (GetDirection 0, 3 or 4), else in front."""
    px, py = at
    s, hs = body_scale(person.age), head_scale(person.age)
    fx, fy = px - int(pi.f32(s * -28.0)), py - int(pi.f32(s * -81.0))
    layers = []
    if shadow:
        layers.append(Layer("shadow", fx - int(pi.f32(s * 34.0)), fy - int(pi.f32(s * 32.0)), percent(s),
                            file=f"Images/{SHADOW}"))
    babies = []
    if person.babies > 0:
        bx = px - int(pi.f32(-7 * s))                 # DrawCarriedItems' place: (int)(zoom * -7) then * Scale
        by = py - int(pi.f32(-33 * s))
        spots = [(bx - 10, by - 10), (bx - 15, by - 5), (bx - 10, by - 1)]
        babies = [Layer("baby", x, y, 100, image=CARRYING, col=BABY_CELL % 13, row=BABY_CELL // 13)
                  for x, y in spots[:min(3, person.babies)]]
    direction = facing(frame)
    behind = direction in (0, 3, 4)
    if behind:
        layers += babies
    hx, hy = link("head", "next", turn, person.sex, person.head, hs)
    nx, ny = link("body", "next", frame, person.sex, person.body, s)
    bx, by = fx - nx, fy - ny
    layers.append(_body_layer(person, frame, bx, by, percent(s), patched, False))
    vx, vy = link("body", "prev", frame, person.sex, person.body, s)
    entry = link_entry("head", turn, person.sex)
    col = entry["cell"] + (12 if person.age >= OLD_HEAD_AGE else 0)
    layers.append(Layer("head", bx + vx - hx, by + vy - hy, percent(hs), image=entry["image"], col=col,
                        row=person.head))
    if not behind:
        layers += babies
    return layers


def event_plan(person: Person, facing_you: bool = False, scale: float = 1.0, patched: bool = False,
               at: tuple = (0, 0)) -> list[Layer]:
    """CVillager::DrawEventVillager(at, ..., scale, facing_you): the shadow, the standing body (frame 46) and the
    head turned (2) or facing you (5). Facing you, the body hangs from its neck at `at`; else it stands on it."""
    px, py = at
    s = pi.f32(body_scale(person.age) * scale)
    hs = pi.f32(head_scale(person.age) * scale) if person.age < CHILD_AGE else scale
    layers = [Layer("shadow", px - int(pi.f32(s * 34.0)), py - int(pi.f32(s * 32.0)), int(pi.f32(s * 100.0)),
                    file=f"Images/{SHADOW}")]
    turn = 5 if facing_you else 2
    hpct = int(pi.f32(hs * 100.0))
    nx, ny = link("body", "next", EVENT_FRAME, person.sex, person.body, s)
    vx, vy = link("body", "prev", EVENT_FRAME, person.sex, person.body, s)
    ox, oy = (vx, vy) if facing_you else (nx, ny)
    bx, by = px - ox, py - oy
    layers.append(_body_layer(person, EVENT_FRAME, bx, by, int(pi.f32(s * 100.0)), patched, False))
    hx, hy = link("head", "next", turn, person.sex, person.head, hs)
    nkx, nky = (px, py) if facing_you else (bx + vx, by + vy)
    entry = link_entry("head", turn, person.sex)
    col = turn + (12 if person.age >= OLD_HEAD_AGE else 0)     # the code adds the turn itself, not the cell
    layers.append(Layer("head", nkx - hx, nky - hy, hpct, image=entry["image"], col=col, row=person.head))
    return layers


def tree_plan(person: Person, at: tuple = (0, 0)) -> list[Layer]:
    """CFamilyTreeScene::DrawPeep(at, sex, head, body, 1.0): the big body (frame 56) hanging from its neck at
    `at` and the big head turned 13 on it, always the young head (no age is used), at full size. Nothing in the
    Family Tree goes through the patcher's body redirect, so an expansion outfit draws row 49 there."""
    px, py = at
    vx, vy = link("body", "prev", DETAIL_FRAME, person.sex, person.body, 1.0)
    entry = link_entry("body", DETAIL_FRAME, person.sex)
    body = Layer("body", px - vx, py - vy, 100, image=entry["image"], col=entry["cell"], row=person.body)
    hx, hy = link("head", "next", TREE_HEAD, person.sex, person.head, 1.0)
    head_entry = link_entry("head", TREE_HEAD, person.sex)
    head = Layer("head", px - hx, py - hy, 100, image=head_entry["image"], col=head_entry["cell"], row=person.head)
    return [body, head]


def tray_outfit_plan(sex: int, picture: int, in_tray: bool = True, at: tuple = (0, 0)) -> list[Layer]:
    """CInventoryManager::DrawItem for a Male or Female Outfit (49h / 4Ah): column 14 of the sex's actions sheet,
    the outfit's picture as the row, at 70% in the tool tray (100% in the store), centred on `at` by the cell's
    size and moved down 2."""
    image = 582 if sex == MALE else 578
    px, py = at
    w, h = 91, 91                                   # the actions sheet's cell (1365 / 15, 4550 / 50)
    x, y = px - w // 2, py - h // 2 + 2
    return [Layer("outfit", x, y, 70 if in_tray else 100, image=image, col=14, row=picture, centre=True)]


