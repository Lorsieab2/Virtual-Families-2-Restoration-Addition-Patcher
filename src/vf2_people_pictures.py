class GameArt:
    """A game folder's pictures (its Images), read once each; `patched` when it holds the patcher's frames for
    the expansion outfits."""

    def __init__(self, game_folder) -> None:
        self.folder = Path(game_folder) if game_folder else None
        self._pictures: dict[str, pi.Image] = {}
        self._grids: dict[int, tuple] = {}

    @property
    def images(self) -> Path | None:
        return self.folder / "Images" if self.folder is not None else None

    def present(self) -> bool:
        return self.images is not None and all((self.images / name).is_file() for name in required_files())

    def missing(self) -> list[str]:
        if self.images is None:
            return list(required_files())
        return [name for name in required_files() if not (self.images / name).is_file()]

    @property
    def patched(self) -> bool:
        """The patcher's expansion outfit frames are there (both sexes, every role)."""
        if self.folder is None:
            return False
        return all((self.folder / _expansion_frame(sex, 50, image, 0)).is_file()
                   for sex, image in ((MALE, 581), (MALE, 582), (MALE, 583), (FEMALE, 577), (FEMALE, 578),
                                      (FEMALE, 579))) and \
            all((self.folder / _detail_frame(sex, 50)).is_file() for sex in (MALE, FEMALE))

    def picture(self, relative: str) -> pi.Image:
        key = relative.replace("\\", "/").casefold()
        if key not in self._pictures:
            if self.folder is None:
                raise pi.PictureError("No game folder was chosen.")
            path = self.folder / relative
            if not path.is_file():
                raise pi.PictureError(f"The game picture {relative} was not found in {self.folder}.")
            self._pictures[key] = pi.load_png(path)
        return self._pictures[key]

    def grid(self, image: int) -> tuple:
        """(files, cell width, cell height, columns per file, rows per file) as ldwImageGrid's constructors make
        them: one file, or the files <prefix><x><y>.png side by side, cells of the total size / columns, rows."""
        if image not in self._grids:
            name, cols, rows, across, down = IMAGES[image]
            if across * down == 1:
                sheet = self.picture(f"Images/{name}")
                self._grids[image] = ([[f"Images/{name}"]], sheet.width // cols, sheet.height // rows, cols, rows)
            else:
                files = [[f"Images/{name}{x}{y}.png" for x in range(across)] for y in range(down)]
                widths = [self.picture(files[0][x]).width for x in range(across)]
                heights = [self.picture(files[y][0]).height for y in range(down)]
                cw, ch = sum(widths) // cols, sum(heights) // rows
                self._grids[image] = (files, cw, ch, widths[0] // cw, heights[0] // ch)
        return self._grids[image]

    def cell(self, image: int, col: int, row: int) -> tuple[pi.Image, tuple]:
        """ldwImageGrid::GetCellRect(col, row): the file the cell is in and its rectangle; a column or row past
        the grid's last is the last."""
        name, cols, rows, across, down = IMAGES[image]
        files, cw, ch, per_x, per_y = self.grid(image)
        if across * down > 1:
            index = (row // per_y) * across + col // per_x
            if index >= across * down:
                index %= across * down
            col, row = col % per_x, row % per_y
            path = files[index // across][index % across]
        else:
            path = files[0][0]
        col = col if col < cols else cols - 1
        row = row if row < rows else rows - 1
        return self.picture(path), (col * cw, row * ch, col * cw + cw, row * ch + ch)

    def piece(self, layer: Layer) -> pi.Image:
        """The layer's pixels as the game puts them on the screen (scaled by its own blitter)."""
        if layer.file is not None:
            picture = self.picture(layer.file)
            rect = (0, 0, picture.width, picture.height)
        else:
            picture, rect = self.cell(layer.image, layer.col, layer.row)
        return pi.game_scaled_cell(picture, rect, layer.percent)


def required_files() -> tuple:
    """The game pictures the Picture Maker reads (Images\\...)."""
    names = []
    for name, cols, rows, across, down in IMAGES.values():
        if across * down == 1:
            names.append(name)
        else:
            names += [f"{name}{x}{y}.png" for y in range(down) for x in range(across)]
    return tuple(names) + (SHADOW,)


def render(art: GameArt, plan: list[Layer]) -> pi.Image:
    """The plan drawn in order on a clear canvas just big enough for it."""
    placed = [(*where(art, layer), piece) for layer in plan for piece in [art.piece(layer)]]
    if not placed:
        return pi.Image(1, 1)
    left = min(x for x, _y, _p in placed)
    top = min(y for _x, y, _p in placed)
    right = max(x + p.width for x, _y, p in placed)
    bottom = max(y + p.height for _x, y, p in placed)
    canvas = pi.Image(max(1, right - left), max(1, bottom - top))
    for x, y, piece in placed:
        canvas.draw(piece, x - left, y - top)
    return canvas


def where(art: GameArt, layer: Layer) -> tuple[int, int]:
    """Where the blitter puts the layer's top-left: its place, moved by half the shrink when it centres
    (BlitRectWithAlpha: x -= (w' - w) / 2 in C's division, w' = trunc(w * s))."""
    if not layer.centre or layer.percent == 100:
        return layer.x, layer.y
    if layer.file is not None:
        picture = art.picture(layer.file)
        w, h = picture.width, picture.height
    else:
        _picture, (left, top, right, bottom) = art.cell(layer.image, layer.col, layer.row)
        w, h = right - left, bottom - top
    s = pi.f32(layer.percent / 100.0)
    dw, dh = int(pi.f32(w * s)), int(pi.f32(h * s))
    return layer.x - int((dw - w) / 2), layer.y - int((dh - h) / 2)


