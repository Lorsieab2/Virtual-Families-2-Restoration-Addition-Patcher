def _fnv(data: bytes) -> int:
    h = 0xCBF29CE484222325
    for byte in data:
        h = ((h ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def read_outfit_sidecar(raw: bytes, save: bytes) -> list | None:
    """The Outfit Pictures file (runtime/native/b200outfits: "VF2OUTFT", version 1, 188 bytes, checksummed) when
    it describes exactly this save file (its FNV-1a 64 and size): the 9 places' pictures (-1: not known)."""
    if len(raw) != SIDECAR_SIZE or raw[:8] != b"VF2OUTFT" or raw[12:20] != b"VF2B200\0":
        return None
    version, size = struct.unpack_from("<I", raw, 8)[0], struct.unpack_from("<I", raw, 20)[0]
    if version != 1 or size != SIDECAR_SIZE:
        return None
    if struct.unpack_from("<Q", raw, SIDECAR_SIZE - 8)[0] != _fnv(raw[:SIDECAR_SIZE - 8]):
        return None
    if struct.unpack_from("<Q", raw, 24)[0] != _fnv(save) or struct.unpack_from("<I", raw, 32)[0] != len(save):
        return None
    return list(struct.unpack_from(f"<{TRAY_PLACES}i", raw, 36 + TRAY_PLACES * 8 + 9 * 4))


def tray_outfits(save: bytes, sidecar: bytes | None) -> list[TrayOutfit]:
    """The Male and Female Outfits in the save's tool tray, each with the picture the game shows for it: its own
    (the patcher's Outfit Pictures file), else the last one of its sex bought (the original game's one field per
    sex, CInventoryManager +468h / +46Ch)."""
    tray = 8 + GS_TOOL_TRAY
    inventory = 8 + GS_INVENTORY
    stock = {MALE: struct.unpack_from("<i", save, inventory + INV_MALE_PICTURE)[0],
             FEMALE: struct.unpack_from("<i", save, inventory + INV_FEMALE_PICTURE)[0]}
    own = read_outfit_sidecar(sidecar, save) if sidecar else None
    out = []
    for place in range(TRAY_PLACES):
        item = struct.unpack_from("<i", save, tray + 8 * place)[0]
        if item not in (MALE_OUTFIT, FEMALE_OUTFIT):
            continue
        sex = MALE if item == MALE_OUTFIT else FEMALE
        mine = own[place] if own is not None else -1
        picture = mine if mine >= 0 else stock[sex]
        if picture < 0:
            continue                                  # a picture of -1 draws the plain outfit icon, not a body
        out.append(TrayOutfit(place, sex, picture, mine >= 0))
    return out


def outfit_sidecar_path(save_folder: Path, slot: int) -> Path:
    return Path(save_folder) / OUTFITS_FOLDER / f"Virtual Families 2{slot}.ldw.dat"
