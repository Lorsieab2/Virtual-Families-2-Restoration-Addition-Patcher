"""The Picture Maker's family members, drawn exactly as Virtual Families 2 draws them.

Every rule here is the game's own code (the B200 desktop object files, which keep their symbols), and
tests/test_picture_maker.py runs that code under emulation (tests/vf2_people_emu.py) and compares:

* A family member is two cells: a body cell and a head cell. The body sheets are the outfits: one row per body
  value (0-49; 0-31 the store's Discount outfits, 32-43 Department, 44-49 Designer: CVillager::GenCommonBodyType,
  GenUncommonBodyType and GenRareBodyType, which CInventoryManager::MaybeUpdateOutfits stocks the three
  outfits of each sex with), one column per body frame. The head sheets hold one row per head value (0-49: the
  hairstyle and face; the patcher's store sells all 50 of each sex as its 100 hairstyles), one column per head
  turn. Skin and hair are drawn in the cells: nothing is tinted.
* Body frames (EAnimFrame 0-56): 0-31 walking (8 frames each NE, SE, SW, NW) on <sex>_bodies00.png, 32-46 actions
  on <sex>_actions00.png, 47-55 sitting and lying on <sex>_sit00.png, 56 the Details screen's big body on
  highrez_bodies_final2.png (one column per sex). Head turns 0-11 on <sex>_heads00/10.png, 12-14 the Details
  screen's big heads on bigheads00/10.png (columns 0-2 male, 3-5 female).
* Where they go: CAnimManager's link tables (src/vf2_people_links.json, made by running CAnimManager::LoadAssets
  over the game's Assets\\animpts.dat). The body is put with its "next" point on the place the game gives; the
  head with its "next" point on the body's "prev" point (the neck). GetScaledLinkTo{Next,Prev}Pt scale a point
  as (int)(p * s + 0.5), each step a float.
* Life stages (CVillager::Scale and the head scale every draw uses): below age 280 (14 years) the body is drawn
  at age / 700 + 0.5 of its size and the head at (age / 14 + 80) / 100; from 280 both are full size. From age
  900 (45 years) the head comes from the old half of the head sheet (heads10, bigheads10): its column plus half
  the sheet's columns. That is all the game does with age: babies, toddlers, children and teens are the same
  cells drawn smaller, growing every age unit.
* Babies on the way: while a mother is expecting (CVillagerState+24h), CVillagerManager::DrawCarriedItems draws
  cell 3 of carrying.png once for each baby (CVillagerState+28h, 1-3) beside her.
* The patcher's expansion outfits (body values 50-53, the B97 GetOutfit hook) are drawn, in a patched game, from
  Images\\VillagerBodies\\<Sex>\\Body_<NN>\\<bodies|actions|sit>\\Frame<NN>.png and, on the Details screen, from
  Images\\VillagerDetailBodies\\<Sex>\\Body_<NN>\\Frame00.png, each where the stock cell would go
  (vf2_villager_body_frames.cpp, generated by work/patch_mobile_furniture_pack.py: VF2DrawVillagerBodyFrameImpl
  and VF2DrawSceneVillagerBodyFrameImpl; the frames' offsets are 0). The link points stay row 49's (the stock
  clamp). The original game has no rows past 49: GetCellRect draws row 49 for them.

Nothing here writes anything but the PNGs the player saves; saves and game folders are only read.
"""
