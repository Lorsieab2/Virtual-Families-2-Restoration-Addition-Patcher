def tier(body: int) -> str:
    """The store tier a body value comes from (the generators MaybeUpdateOutfits stocks the store with)."""
    if body in EXPANSION_BODIES:
        return "the patcher's Holiday outfits"
    if 0 <= body <= 31:
        return "Discount"
    if 32 <= body <= 43:
        return "Department"
    if 44 <= body <= 49:
        return "Designer"
    return "not a body the game makes"


def outfit_name(sex: int, body: int) -> str:
    """The patcher's Clothing and Hairstyles store name of a body value (outfit_store_entries)."""
    holiday = "Holiday " if body in EXPANSION_BODIES else ""
    return f"{SEXES[sex]} {holiday}Outfit Body {body:02d}"


def hairstyle_name(sex: int, head: int) -> str:
    """The patcher's store name of a head value (head_store_entries: its 100 hairstyles, 50 a sex)."""
    return f"{SEXES[sex]} Hairstyle {head:02d}"


def stage(age: int) -> str:
    """The family's words for an age (the game itself only scales below 14 and turns the head old at 45)."""
    years = age // YEAR
    if years < 1:
        return "baby"
    if years < 3:
        return "toddler"
    if years < 13:
        return "child"
    if years < 20:
        return "teen"
    if age >= OLD_HEAD_AGE:
        return "elder"
    return "adult"


# ------------------------------------------------------------------ the game's numbers


def body_scale(age: int) -> float:
    """CVillager::Scale: age / 700 + 0.5 below age 280 (float steps), else 1."""
    if age < CHILD_AGE:
        return pi.f32(pi.f32(age / 700.0) + 0.5)
    return 1.0


def head_scale(age: int) -> float:
    """The head's scale in every draw: (age / 14 + 80) / 100 below age 280 (float steps), else 1."""
    if age < CHILD_AGE:
        return pi.f32(pi.f32(pi.f32(age / 14.0) + 80.0) / 100.0)
    return 1.0


def percent(scale: float) -> int:
    """A scale as the whole percent the window's scaled draw takes: (int)(scale * 100), a float product."""
    return int(pi.f32(scale * 100.0))


_LINKS: dict | None = None


def links() -> dict:
    global _LINKS
    if _LINKS is None:
        _LINKS = json.loads(LINKS_FILE.read_text(encoding="utf-8"))
    return _LINKS


def link_entry(part: str, key: int, sex: int) -> dict:
    return links()[part][f"{key}/{1 if sex else 0}"]


def link(part: str, which: str, key: int, sex: int, row: int, scale: float) -> tuple[int, int]:
    """CAnimManager::GetScaledLinkTo{Next,Prev}Pt: a row of 50 or more uses row 49."""
    points = link_entry(part, key, sex)[which]
    row = row if row < ROWS else ROWS - 1
    x, y = points[row] if len(points) > 1 else points[0]
    return pi.scaled_link(x, scale), pi.scaled_link(y, scale)


def facing(frame: int) -> int:
    """CAnimManager::GetDirection(EAnimFrame), -1 when the game's table has none."""
    return int(links()["facing"].get(str(frame), -1))


